#!/usr/bin/env bash
# Runs INSIDE debian:bookworm-slim (as root): installs the pinned font packages, copies the curated
# set into OUT, converts FontAwesome 7.2 Free to TTF, and checks the result against
# tools/fonts/SHA256SUMS. Used by tools/fonts/fetch.sh (local/CI) and the Dockerfile fonts stage.
#
# The set mirrors what Chrome actually used in the legacy reference image (see the /BaseFont
# names in tests/fixtures/golden/bodies/*.pdf): Liberation Sans for Mermaid's default stack
# ("trebuchet ms",verdana,arial,sans-serif resolves to arial -> Liberation Sans), DejaVu Sans
# for Arabic/Hebrew, Loma for Thai, WenQuanYi Zen Hei for CJK, Noto Color Emoji, FontAwesome 7.2
# Free.
# File-name prefixes fix the load order, which is merman's family and glyph fallback order.
#
# Usage: install.sh OUT_DIR [FA_TABLE]   (FA_TABLE: where to write the name -> codepoint table)
set -euo pipefail

OUT="$1"
TABLE="${2:-/dev/null}"
HERE="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$OUT"

export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq --no-install-recommends ca-certificates curl python3-fonttools python3-brotli \
  fonts-liberation=1:1.07.4-11 fonts-dejavu-core=2.37-6 fonts-freefont-ttf=20120503-10 \
  fonts-tlwg-loma-ttf=1:0.7.3-1 \
  fonts-wqy-zenhei=0.9.45-8 fonts-noto-color-emoji=2.042-0+deb12u1 >/dev/null

rm -f "$OUT"/*.tt[fc] "$OUT"/*.otf
cp_font() { cp "$1" "$OUT/$2"; }
cp_font /usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf 10-LiberationSans-Regular.ttf
cp_font /usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf    11-LiberationSans-Bold.ttf
cp_font /usr/share/fonts/truetype/liberation/LiberationSans-Italic.ttf  12-LiberationSans-Italic.ttf
cp_font /usr/share/fonts/truetype/liberation/LiberationSans-BoldItalic.ttf 13-LiberationSans-BoldItalic.ttf
cp_font /usr/share/fonts/truetype/dejavu/DejaVuSans.ttf                20-DejaVuSans.ttf
cp_font /usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf           21-DejaVuSans-Bold.ttf
cp_font /usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf            22-DejaVuSansMono.ttf
cp_font /usr/share/fonts/truetype/tlwg/Loma.ttf                        25-Loma.ttf
cp_font /usr/share/fonts/truetype/freefont/FreeSans.ttf                30-FreeSans.ttf
cp_font /usr/share/fonts/truetype/freefont/FreeSerif.ttf               31-FreeSerif.ttf
cp_font /usr/share/fonts/truetype/wqy/wqy-zenhei.ttc                   40-WenQuanYiZenHei.ttc
cp_font /usr/share/fonts/truetype/noto/NotoColorEmoji.ttf              50-NotoColorEmoji.ttf

tmp=$(mktemp -d)
curl -fsSL -o "$tmp/fa.tgz" https://registry.npmjs.org/@fortawesome/fontawesome-free/-/fontawesome-free-7.2.0.tgz
echo "188c1053ce422ad1f934d7df242a973fcb89636d  $tmp/fa.tgz" | sha1sum -c --quiet
tar -xzf "$tmp/fa.tgz" -C "$tmp"
python3 - "$tmp/package" "$OUT" "$TABLE" <<"PY"
import json, sys
from fontTools.ttLib import TTFont
pkg, out, table = sys.argv[1:]
for src, dst in [("fa-solid-900", "60-FontAwesome7Free-Solid.ttf"),
                 ("fa-regular-400", "61-FontAwesome7Free-Regular.ttf"),
                 ("fa-brands-400", "62-FontAwesome7Brands-Regular.ttf")]:
    f = TTFont(f"{pkg}/webfonts/{src}.woff2", recalcTimestamp=False)  # reproducible SHA256SUMS
    f.flavor = None
    f.save(f"{out}/{dst}")
# name -> codepoint + styles (s=solid, r=regular, b=brands), aliases included.
icons = json.load(open(f"{pkg}/metadata/icon-families.json"))
rows = {}
for name, icon in icons.items():
    styles = icon.get("familyStylesByLicense", {}).get("free", [])
    flags = "".join(sorted({s["style"][0] for s in styles if s.get("family") == "classic"}))
    if not flags:
        continue
    for n in [name] + icon.get("aliases", {}).get("names", []):
        rows.setdefault(n, (icon["unicode"], flags))
with open(table, "w", newline="\n") as t:
    t.write("# generated by tools/fonts/fetch.sh from @fortawesome/fontawesome-free 7.2.0 metadata\n")
    for n in sorted(rows):
        t.write(f"{n} {rows[n][0]} {rows[n][1]}\n")
PY
rm -rf "$tmp"

cd "$OUT"
sha256sum *.tt[fc] > SHA256SUMS
# The pinned set must be byte-identical everywhere (it is part of the cache-key fingerprint).
# Deliberately changing the set? Copy the new OUT/SHA256SUMS over tools/fonts/SHA256SUMS.
if ! diff <(tr -d '\r' < "$HERE/SHA256SUMS") SHA256SUMS; then
  echo "font set differs from tools/fonts/SHA256SUMS" >&2
  exit 1
fi
du -ch *.tt[fc] | tail -1
